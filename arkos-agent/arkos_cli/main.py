_PROFILE_NAME_RE = r"^[a-z0-9][a-z0-9_-]{0,63}$"


def _inside_mcp_add_args(argv: list, index: int) -> bool:
    """True once argv reaches `arkos mcp add ... --args <command argv>`.

    ``mcp add --args`` is command-argv passthrough. Flags after that point
    belong to the child MCP command (for example Docker MCP Toolkit's
    ``--profile``), not to Arkos' own profile selector.
    """
    try:
        mcp_index = argv.index("mcp", 0, index)
        argv.index("add", mcp_index + 1, index)
    except ValueError:
        return False
    return True


def _scan_profile_flag(argv: list) -> tuple:
    """Find -p/--profile/--profile= in argv -> (name, tokens_consumed, index).

    Historically the flag worked even after the subcommand (`arkos chat -p
    coder`), so scan broadly; stop at ``--`` and at the `mcp add --args`
    passthrough region. Values that can't be profile names (pytest's
    ``-p no:xdist``) are rejected so resolve_profile_env never sys.exits on them.
    """
    from arkos_cli._parser import top_level_value_flag_sets

    value_flags, optional_value_flags = top_level_value_flag_sets()
    i = 0
    while i < len(argv):
        arg = argv[i]
        if arg == "--" or (arg == "--args" and _inside_mcp_add_args(argv, i)):
            break
        if arg in {"--profile", "-p"} and i + 1 < len(argv):
            if re.match(_PROFILE_NAME_RE, argv[i + 1]):
                return argv[i + 1], 2, i
            break
        if arg.startswith("--profile="):
            return arg.split("=", 1)[1], 1, i
        takes_value = "=" not in arg and i + 1 < len(argv) and (
            arg in value_flags
            or (arg in optional_value_flags and not argv[i + 1].startswith("-"))
        )
        i += 2 if takes_value else 1
    return None, 0, None


def _resolve_sudo_user_profile_env(name: str) -> str | None:
    """Resolve `sudo arkos -p <name>` against the invoking user's home.

    This runs before argparse, so `--run-as-user` is not available yet. For
    sudo invocations the best signal is SUDO_USER: root is only doing the
    privileged install/start action; the profile store belongs to the user.
    """
    if name == "default" or not hasattr(os, "geteuid") or os.geteuid() != 0:
        return None
    sudo_user = os.environ.get("SUDO_USER", "").strip()
    if not sudo_user or sudo_user == "root":
        return None
    try:
        import pwd

        candidate = Path(pwd.getpwnam(sudo_user).pw_dir) / ".arkos" / "profiles" / name
        return str(candidate) if candidate.is_dir() else None
    except Exception:
        return None


def _under_gateway_supervisor(argv: list) -> bool:
    """A supervisor-launched gateway child must NOT follow the sticky active_profile.

    Each supervised slot has a fixed profile identity: named slots pass
    ``-p <name>`` or pin ARKOS_HOME to the profile dir; a bare invocation
    means "the root ARKOS_HOME profile". If a supervised default-profile
    child read active_profile, switching the active profile (dashboard,
    ``arkos profile use``) would silently redirect the default gateway into
    that profile — adopting its credentials and double-polling a Telegram
    token already owned by that profile's own gateway.

    Markers (see gateway/restart.py ``is_gateway_supervisor_process``):
    ARKOS_SUPERVISED_CHILD (systemd unit / launchd plist / Windows task),
    ARKOS_S6_SUPERVISED_CHILD (legacy s6 container), INVOCATION_ID (systemd
    service children only — consulted ONLY for gateway commands because it is
    inherited by every descendant of a systemd-launched process, e.g.
    self-hosted CI runners), ARKOS_GATEWAY_EXTERNAL_SUPERVISOR (explicit
    opt-in). XPC_SERVICE_NAME is deliberately NOT consulted: interactive macOS
    terminals set it too.
    """
    if os.environ.get("ARKOS_SUPERVISED_CHILD") or os.environ.get("ARKOS_S6_SUPERVISED_CHILD"):
        return True
    is_gateway_cmd = next((a for a in argv if not a.startswith("-")), None) == "gateway"
    if is_gateway_cmd and os.environ.get("INVOCATION_ID"):
        return True
    return os.environ.get(
        "ARKOS_GATEWAY_EXTERNAL_SUPERVISOR", ""
    ).strip().lower() in {"1", "true", "yes", "on"}


def _apply_profile_override() -> None:
    """Pre-parse --profile/-p and set ARKOS_HOME before imports."""
    argv = sys.argv[1:]
    profile_name, consume, profile_index = _scan_profile_flag(argv)

    arkos_home_env = os.environ.get("ARKOS_HOME", "")
    if profile_name is None and arkos_home_env and Path(arkos_home_env).parent.name == "profiles":
        return

    if profile_name is None and not _under_gateway_supervisor(argv):
        try:
            from arkos_constants import get_default_arkos_root

            active_path = get_default_arkos_root() / "active_profile"
            if active_path.exists():
                name = active_path.read_text(encoding="utf-8").strip()
                if name and name != "default":
                    profile_name = name
        except (UnicodeDecodeError, OSError):
            pass

    if profile_name is None:
        return
    try:
        from arkos_cli.profiles import resolve_profile_env

        arkos_home = resolve_profile_env(profile_name)
    except FileNotFoundError as exc:
        arkos_home = _resolve_sudo_user_profile_env(profile_name)
        if not arkos_home:
            print(f"Error: {exc}", file=sys.stderr)
            sys.exit(1)
    except ValueError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        sys.exit(1)
    except Exception as exc:
        print(f"Warning: profile override failed ({exc}), using default", file=sys.stderr)
        return
    os.environ["ARKOS_HOME"] = arkos_home
    if consume > 0 and profile_index is not None:
        start = profile_index + 1
        sys.argv = sys.argv[:start] + sys.argv[start + consume :]


